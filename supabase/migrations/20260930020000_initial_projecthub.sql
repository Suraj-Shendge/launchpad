create or replace function public.settle_auction(p_auction_id uuid)
returns table(auction_id uuid,winner_id uuid,winning_bid numeric)
language plpgsql
security definer
set search_path=public,pg_temp
as $func$
declare
  a public.auctions;
  bid public.auction_bids;
begin
  select * into a from public.auctions where id=p_auction_id for update;
  if not found then raise exception 'Auction not found'; end if;

  if a.status='active' and now() >= a.ends_at then
    select * into bid from public.auction_bids
    where auction_id=a.id
    order by amount desc, created_at asc
    limit 1;

    update public.auctions
    set status='settled',
        winner_id=bid.bidder_id,
        winning_bid=bid.amount,
        updated_at=now()
    where id=a.id;

    return query select a.id,bid.bidder_id,bid.amount;
  elsif a.status='settled' then
    return query select a.id,a.winner_id,a.winning_bid;
  else
    raise exception 'Auction cannot be settled in its current state';
  end if;
end;
$func$;

