create or replace function public.place_bid(p_auction_id uuid,p_amount numeric)
returns public.auction_bids
language plpgsql
set search_path=public,pg_temp
as $func$
declare
  a public.auctions;
  b public.auction_bids;
  minimum numeric;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required';
  end if;

  select * into a from public.auctions where id=p_auction_id for update;
  if not found then raise exception 'Auction not found'; end if;
  if a.status <> 'active' or now() < a.starts_at or now() >= a.ends_at then
    raise exception 'Auction is not active';
  end if;

  minimum := greatest(coalesce(a.current_bid,a.starting_price),a.starting_price) + a.bid_increment;
  if p_amount < minimum then raise exception 'Bid must be at least %',minimum; end if;

  insert into public.auction_bids(auction_id,bidder_id,amount)
  values(a.id,(select auth.uid()),p_amount) returning * into b;

  update public.auctions
  set current_bid=p_amount,updated_at=now()
  where id=a.id;

  return b;
end;
$func$;

