with (security_invoker=true) as
select p.id,p.owner_id as creator_id,p.slug,p.name,p.tagline,p.description,
  p.logo_url,p.website_url,p.social_links,p.status,p.created_at,p.published_at,
  c.id as category_id,c.name as category_name,c.slug as category_slug,
  pr.display_name as creator_name,
  coalesce(array_agg(distinct t.name) filter(where t.name is not null),'{}') as tags,
  exists(
    select 1 from public.promotions x
    join public.promotion_types pt on pt.id=x.type_id
    where x.project_id=p.id and x.status='active' and pt.slug='featured'
  ) as featured,
  exists(
    select 1 from public.promotions x
    join public.promotion_positions pp on pp.id=x.position_id
    where x.project_id=p.id and x.status='active'
      and pp.slug like 'homepage%'
  ) as promoted
from public.projects p
join public.categories c on c.id=p.category_id
join public.profiles pr on pr.id=p.owner_id
left join public.project_tags ptg on ptg.project_id=p.id
left join public.tags t on t.id=ptg.tag_id
group by p.id,c.id,pr.id;
